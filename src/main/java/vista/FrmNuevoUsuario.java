    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // =====================================================
    // 1. VERIFICAR SESIÓN
    // =====================================================

    Usuario usuarioActual = Sesion.getUsuarioActual();

    if (usuarioActual == null) {

        JOptionPane.showMessageDialog(
                this,
                "No hay una sesión activa.",
                "Acceso denegado",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    String rolActual = usuarioActual.getRol();


    // =====================================================
    // 2. OBTENER EL ROL QUE SE QUIERE CREAR
    // =====================================================

    if (cmbRol.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Seleccione un rol.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    String rolNuevo = cmbRol.getSelectedItem().toString();


    // =====================================================
    // 3. NUNCA SE PUEDE CREAR UN OWNER
    // =====================================================

    if ("Owner".equalsIgnoreCase(rolNuevo)) {

        JOptionPane.showMessageDialog(
                this,
                "No se puede crear un Owner desde este sistema.",
                "Acceso denegado",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }


    // =====================================================
    // 4. SOLO OWNER PUEDE CREAR ADMINISTRADORES
    // =====================================================

    if ("Administrador".equalsIgnoreCase(rolNuevo)
            && !"Owner".equalsIgnoreCase(rolActual)) {

        JOptionPane.showMessageDialog(
                this,
                "Solo el Owner puede crear usuarios Administrador.",
                "Acceso denegado",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }


    // =====================================================
    // 5. SOLO OWNER Y ADMINISTRADOR PUEDEN CREAR USUARIOS
    // =====================================================

    if (!"Owner".equalsIgnoreCase(rolActual)
            && !"Administrador".equalsIgnoreCase(rolActual)) {

        JOptionPane.showMessageDialog(
                this,
                "Su rol no tiene permisos para crear usuarios.",
                "Acceso denegado",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }


    // =====================================================
    // 6. OBTENER DATOS DEL FORMULARIO
    // =====================================================

    String usuario = txtUsuario.getText().trim();
    String nombre = txtNombre.getText().trim();
    String password = new String(txtContrasena.getPassword());
    String confirmarPassword =
            new String(txtConfirmarContrasena.getPassword());

    String estado = cmbEstado.getSelectedItem().toString();


    // =====================================================
    // 7. VALIDAR CAMPOS
    // =====================================================

    if (usuario.isEmpty()
            || nombre.isEmpty()
            || password.isEmpty()
            || confirmarPassword.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Complete todos los campos.",
                "Campos incompletos",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }


    // =====================================================
    // 8. CONFIRMAR CONTRASEÑA
    // =====================================================

    if (!password.equals(confirmarPassword)) {

        JOptionPane.showMessageDialog(
                this,
                "Las contraseñas no coinciden.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }


    // =====================================================
    // 9. CREAR OBJETO USUARIO
    // =====================================================

    Usuario nuevoUsuario = new Usuario();

    nuevoUsuario.setUsuario(usuario);
    nuevoUsuario.setNombre(nombre);
    nuevoUsuario.setPassword(password);
    nuevoUsuario.setRol(rolNuevo);
    nuevoUsuario.setEstado(estado);


    // =====================================================
    // 10. REGISTRAR EN BASE DE DATOS
    // =====================================================

    if (usuarioDAO.registrar(nuevoUsuario)) {

        JOptionPane.showMessageDialog(
                this,
                "Usuario registrado correctamente.",
                "Registro exitoso",
                JOptionPane.INFORMATION_MESSAGE
        );

        ventanaUsuarios.actualizarUsuarios();
        ventanaUsuarios.setVisible(true);

        this.dispose();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "No se pudo registrar el usuario.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

