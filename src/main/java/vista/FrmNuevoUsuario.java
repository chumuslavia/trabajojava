    private void configurarRoles() {

    Usuario usuarioActual = Sesion.getUsuarioActual();

    if (usuarioActual == null) {

        JOptionPane.showMessageDialog(
                this,
                "No hay una sesión activa.",
                "Acceso denegado",
                JOptionPane.ERROR_MESSAGE
        );

        btnGuardar.setEnabled(false);
        cmbRol.setEnabled(false);

        return;
    }

    String rolActual = usuarioActual.getRol();

    // Limpiar los roles actuales
    cmbRol.removeAllItems();

    // =====================================================
    // OWNER
    // Puede crear Administradores y demás usuarios
    // NO puede crear otro Owner
    // =====================================================

    if ("Owner".equalsIgnoreCase(rolActual)) {

        cmbRol.addItem("Administrador");
        cmbRol.addItem("Recepción");
        cmbRol.addItem("Médico");
        cmbRol.addItem("Laboratorio");

        return;
    }

    // =====================================================
    // ADMINISTRADOR
    // NO puede crear Administradores
    // Solo usuarios normales
    // =====================================================

    if ("Administrador".equalsIgnoreCase(rolActual)) {

        cmbRol.addItem("Recepción");
        cmbRol.addItem("Médico");
        cmbRol.addItem("Laboratorio");

        return;
    }

    // =====================================================
    // RECEPCIÓN / MÉDICO / LABORATORIO
    // No pueden crear usuarios
    // =====================================================

    cmbRol.setEnabled(false);
    btnGuardar.setEnabled(false);

    JOptionPane.showMessageDialog(
            this,
            "Su rol no tiene permisos para crear usuarios.",
            "Acceso denegado",
            JOptionPane.WARNING_MESSAGE
    );
}

    
    
