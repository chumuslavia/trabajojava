    private void btnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeleccionarActionPerformed
        // TODO add your handling code here:
      modelo.Paciente paciente = obtenerPacienteSeleccionado();

    if (paciente == null) {
        return;
    }

    switch (destino) {

        case "HISTORIA":

            FrmHistoriaClinica historia =
                    new FrmHistoriaClinica(paciente);

            historia.setVisible(true);
            this.dispose();

            break;

        case "ANALISIS":

            FrmAnalisis analisis =
                    new FrmAnalisis(paciente);

            analisis.setVisible(true);
            this.dispose();

            break;

        case "COSTOS":

            FrmCostos costos =
                    new FrmCostos(paciente);

            costos.setVisible(true);
            this.dispose();

            break;

        default:

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se ha definido el módulo de destino.",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

            break;
    }
    }//GEN-LAST:event_btnSeleccionarActionPerformed

