    private void cargarPacientes(String texto) {

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblPacientes.getModel();

    modelo.setRowCount(0);

    java.util.List<modelo.Paciente> pacientes = dao.buscar(texto);

    for (modelo.Paciente p : pacientes) {

        modelo.addRow(new Object[]{
            p.getIdPaciente(),
            p.getDni(),
            p.getNombres(),
            p.getApellidos(),
            p.getTelefono()
        });
    }
}
    private modelo.Paciente obtenerPacienteSeleccionado() {

    int fila = tblPacientes.getSelectedRow();

    if (fila == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Seleccione un paciente.",
                "Aviso",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return null;
    }

    int idPaciente = Integer.parseInt(
            tblPacientes.getValueAt(fila, 0).toString()
    );

    return dao.buscarPorId(idPaciente);
}

