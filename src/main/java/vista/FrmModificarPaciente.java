    private void btnGuardarCambiosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarCambiosActionPerformed
        // TODO add your handling code here:
        
          try {
        Paciente paciente = new Paciente();

        // ID solamente para identificar al paciente.
        // No se modifica.
        paciente.setIdPaciente(Integer.parseInt(lblId.getText()));

        // Datos editables
        paciente.setDni(txtDni.getText().trim());
        paciente.setNombres(txtNombres.getText().trim());
        paciente.setApellidos(txtApellidos.getText().trim());

        paciente.setFechaNacimiento(
                java.sql.Date.valueOf(txtFechaNacimiento.getText().trim())
        );

        paciente.setSexo(cmbSexo.getSelectedItem().toString());
        paciente.setTelefono(txtTelefono.getText().trim());
        paciente.setDireccion(txtDireccion.getText().trim());

        PacienteDAO dao = new PacienteDAO();

        if (dao.modificar(paciente)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Paciente modificado correctamente.",
                    "Éxito",
                    JOptionPane.INFORMATION_MESSAGE
            );

            // Cerrar ventana de modificación
            this.dispose();

            // Volver a FrmPacientes
            FrmPacientes ventanaPacientes = new FrmPacientes();
            ventanaPacientes.setVisible(true);

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo modificar el paciente.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(
                this,
                "La fecha debe tener el formato AAAA-MM-DD.",
                "Fecha incorrecta",
                JOptionPane.WARNING_MESSAGE
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al modificar el paciente: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnGuardarCambiosActionPerformed

