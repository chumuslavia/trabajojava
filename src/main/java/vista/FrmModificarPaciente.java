    private void cargarPaciente(int idPaciente) {

    PacienteDAO dao = new PacienteDAO();

    Paciente p = dao.buscarPorId(idPaciente);

    if (p == null) {

        JOptionPane.showMessageDialog(
                this,
                "No se encontró el paciente.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    lblId.setText(String.valueOf(p.getIdPaciente()));
    txtDni.setText(p.getDni());
    txtNombres.setText(p.getNombres());
    txtApellidos.setText(p.getApellidos());
    txtFechaNacimiento.setText(p.getFechaNacimiento().toString());
    cmbSexo.setSelectedItem(p.getSexo());
    txtTelefono.setText(p.getTelefono());
    txtDireccion.setText(p.getDireccion());
}

